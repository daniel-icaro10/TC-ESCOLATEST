/* SQL escrito para o SQLite -> SQL do Postgres */
function traduzir(sql) {
  sql = sql
    .replace(/datetime\('now'\)/gi, AGORA_UTC)
    .replace(/date\('now',\s*'localtime'\)/gi, "to_char(localtimestamp, 'YYYY-MM-DD')")
    .replace(/^\s*BEGIN\s+IMMEDIATE\b/i, 'BEGIN');
  let out = '', n = 0;
  for (let i = 0; i < sql.length;) {
    const c = sql[i];
    if (c === "'" || c === '"') {   // texto entre aspas passa sem mudança
      let j = i + 1;
      while (j < sql.length) { if (sql[j] === c) { if (sql[j + 1] === c) { j += 2; continue; } break; } j++; }
      out += sql.slice(i, j + 1); i = j + 1;
    } else if (c === '?') { out += '$' + (++n); i++; }
    else if (/[A-Za-z_]/.test(c)) {
      let j = i; while (j < sql.length && /\w/.test(sql[j])) j++;
      const palavra = sql.slice(i, j);
      // apelidos como turmaId: sem aspas o Postgres devolveria "turmaid"
      out += /^[a-z][a-z0-9_]*[A-Z]\w*$/.test(palavra) ? `"${palavra}"` : palavra;
      i = j;
    } else { out += c; i++; }
  }
  return out;
}

function abrirPostgres(url, { fusoHorario = process.env.TZ || 'America/Sao_Paulo', espera = 60000 } = {}) {
  const sinal = new SharedArrayBuffer(4);
  const contador = new Int32Array(sinal);
  const { port1, port2 } = new MessageChannel();
  const worker = new Worker(path.join(__dirname, 'db-postgres-worker.js'), {
    workerData: { porta: port2, sinal, url, fusoHorario }, transferList: [port2]
  });
  worker.unref();
  let proximoId = 0;

  function chamar(sql, params) {
    const id = ++proximoId;
    let visto = Atomics.load(contador, 0);
    port1.postMessage({ id, sql, params });
    const limite = Date.now() + espera;
    for (;;) {
      let msg;
      while ((msg = receiveMessageOnPort(port1))) {
        if (msg.message.id !== id) continue;   // resposta atrasada de um pedido que já desistiu
        const r = msg.message;
        if (r.erro) {
          const e = new Error(`Banco de dados: ${r.erro.message}`);
          e.code = r.erro.code; e.detail = r.erro.detail; e.sql = sql;
          throw e;
        }
        return r;
      }
      const falta = limite - Date.now();
      if (falta <= 0) throw new Error('O banco de dados não respondeu a tempo. Confira a conexão (DATABASE_URL).');
      Atomics.wait(contador, 0, visto, falta);
      visto = Atomics.load(contador, 0);
    }
  }

  const prep = p => p.map(v => v === undefined ? null : typeof v === 'boolean' ? (v ? 1 : 0) : v);
  const cache = new Map();
  const pg = sql => { let s = cache.get(sql); if (s === undefined) { s = traduzir(sql); cache.set(sql, s); } return s; };
  let profundidade = 0;

  const api = {
    tipo: 'postgres',
    arquivo: null,
    todos: (sql, ...p) => chamar(pg(sql), prep(p)).rows,
    um: (sql, ...p) => chamar(pg(sql), prep(p)).rows[0] || null,
    rodar: (sql, ...p) => {
      let q = pg(sql);
      if (/^\s*INSERT\b/i.test(q) && !/\bRETURNING\b/i.test(q)) q += ' RETURNING *';   // o id do registro novo
      const r = chamar(q, prep(p));
      const id = r.rows[0] && r.rows[0].id != null ? Number(r.rows[0].id) : null;
      return { id, mudancas: r.count };
    },
    exec: sql => { chamar(pg(sql), []); },
    transacao(fn) {
      if (profundidade) return fn();   // já está dentro de uma transação
      chamar('BEGIN', []); profundidade++;
      try { const r = fn(); profundidade--; chamar('COMMIT', []); return r; }
      catch (e) { profundidade--; try { chamar('ROLLBACK', []); } catch (e2) { /* conexão caiu */ } throw e; }
    },
    config(chave, padrao = null) { const r = api.um('SELECT valor FROM config WHERE chave = ?', chave); return r ? JSON.parse(r.valor) : padrao; },
    salvarConfig(chave, valor) { api.rodar('INSERT INTO config (chave, valor) VALUES (?, ?) ON CONFLICT(chave) DO UPDATE SET valor = excluded.valor', chave, JSON.stringify(valor)); },
    backup: () => null,   // no Postgres o backup é do provedor (Render) ou do pg_dump na VPS
    /* cópia de todos os dados em JSON (botão "Baixar backup" do portal) */
    exportar() {
      const tabelas = api.todos("SELECT table_name AS nome FROM information_schema.tables WHERE table_schema = current_schema() AND table_type = 'BASE TABLE' ORDER BY table_name").map(t => t.nome);
      const dados = {};
      tabelas.forEach(t => { dados[t] = chamar(`SELECT * FROM "${t.replace(/"/g, '')}"`, []).rows; });
      return { geradoEm: new Date().toISOString(), banco: 'postgres', tabelas: dados };
    },
    fechar() { try { chamar(null, null); } catch (e) { /* já fechado */ } worker.terminate(); }
  };

  // migrações: a versão do banco fica na tabela versao_banco
  chamar('CREATE TABLE IF NOT EXISTS versao_banco (versao INTEGER NOT NULL)', []);
  let versao = (api.um('SELECT versao FROM versao_banco') || {}).versao;
  if (versao == null) { api.rodar('INSERT INTO versao_banco (versao) VALUES (0)'); versao = 0; }
  for (let v = versao; v < MIGRACOES_PG.length; v++) {
    api.transacao(() => { chamar(MIGRACOES_PG[v], []); chamar('UPDATE versao_banco SET versao = $1', [v + 1]); });
  }
  return api;
}

