/* Banco de dados Postgres (usado quando existe a variável DATABASE_URL, ex.: Render ou VPS).

   O resto do servidor continua escrevendo o SQL do jeito do SQLite e usando a mesma API síncrona
   (todos, um, rodar, exec, transacao). Aqui:
   - o SQL é traduzido para o Postgres (parâmetros ? viram $1, $2..., apelidos camelCase ganham
     aspas para não virarem minúsculas, datetime('now') vira now() etc.);
   - as consultas rodam numa thread separada (db-postgres-worker.js) e o servidor espera a resposta,
     como já acontecia com o SQLite. Assim nenhuma rota precisou mudar. */
